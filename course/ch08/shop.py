# 指定檔案編碼為 UTF-8，確保程式能正確處理中文文字
# -*- coding: utf-8 -*-
# 定義商品資料元組（tuple），每個項目包含：(品名, 單價, 數量)
data = (('香蕉', 34, 2), ('芭樂', 28, 3), ('水梨', 50, 2))
# 建立一個空的列表（list），用來儲存每樣商品的小計金額
total = []
# 印出表格的標題列，使用 \t (Tab) 進行欄位分隔與對齊
print ('品  名\t數  量\t單  價\t小  計')
for t1 in data:
    # 使用 for 迴圈逐一取出 data 中的每一組商品資料 (元組)
    # 解構賦值：將 t1 的三個元素分別解包指派給 name (品名)、s1 (單價)、s2 (數量)
    name,s1,s2 = t1
    # 計算該項商品的小計金額 (單價 * 數量)，並將結果新增至 total 列表中
    total.append(s1 * s2)
    # 印出單列商品資訊：字串（String）：預設靠左對齊。 數字（Number）：預設靠右對齊
    # `print()` 並透過格式化對齊時：
    # - {name:>4}: 品名靠右對齊，佔據 4 個字元寬度 
    # - {s1:8}: 單價靠右對齊，佔據 8 個字元寬度 
    # - {s2:8}: 數量靠右對齊，佔據 8 個字元寬度 
    # - {total[-1]:8}: 印出最新加入的小計金額 (-1 索引最後一個(total 列表的最後一個元素))，靠右對齊佔 8 個字元
    print(f'{name:>4}{s1:8}{s2:8}{total[-1]:8}')
# 使用 sum(total) 加總所有商品的小計，並靠右對齊格式化印出總金額（寬度占 23 個字元）
print(f'總  計:{sum(total):23}')     