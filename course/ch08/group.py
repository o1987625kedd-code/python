# 這段程式碼主要展示了 **Set（集合）** 去除重複資料，以及進行集合運算（交集與聯集）的實際應用。
# 建立熱門音樂社的原始名單串列 (List)，包含重複報名的姓名（例如：'王一'、'張三'出現兩次）
g1=['林二','王一','張三','趙六','王一','李四','張三','陳五']
 
# 建立流行音樂社的原始名單串列 (List)，包含重複報名的姓名（例如：'柯七'出現兩次）
g2=['鄭十','趙六','劉千','廖八','柯七','張三','王一','呂九','柯七','蔡百']
 
# 使用 set() 將熱門音樂社名單轉為集合 (Set)，自動剔除重複的人名，得到單一不重複的名單
s1 = set(g1)
 
# 印出熱門音樂社的「原始人數 len(g1)」與「去除重複後的正確人數 len(s1)」
print(f'熱門音樂社原來人數：{len(g1)}人  正確人數：{len(s1)}人')
 
# 使用 set() 將流行音樂社名單轉為集合 (Set)，自動剔除重複的人名
s2 = set(g2)
 
# 印出流行音樂社的「原始人數 len(g2)」與「去除重複後的正確人數 len(s2)」
print(f'流行音樂社原來人數：{len(g2)}人  正確人數：{len(s2)}人')
 
# 使用 .intersection() 取交集（也可用 s1 & s2），找出同時存在於兩個社團（重複參加）的名單
s3 =s1.intersection(s2)
 
# 印出兩社重複參加的名單（集合形式，例如：{'張三', '王一', '趙六'}）
print(f'重複參加社團名單：{s3}')
 
# 使用 .union() 取聯集（也可用 s1 | s2），將兩個社團的名單合併，並自動去除跨社重複的人名
# s4 =s1.union(s2)
s4 =s1|s2
# 印出合併後且不重複的總人數 len(s4)
print(f'合併後社團人數：{len(s4)}人')
print(s4)